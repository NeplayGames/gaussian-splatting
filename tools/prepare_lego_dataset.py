import argparse
import json
import shutil
from pathlib import Path


IMAGE_EXTENSIONS = (".png", ".jpg", ".jpeg")


def find_blender_roots(root: Path) -> list[Path]:
    return sorted({path.parent for path in root.rglob("transforms_train.json")})


def choose_root(root: Path, requested: Path | None) -> Path:
    if requested:
        dataset_root = requested if requested.is_absolute() else root / requested
        if not (dataset_root / "transforms_train.json").is_file():
            raise SystemExit(f"transforms_train.json was not found in {dataset_root}")
        return dataset_root

    candidates = find_blender_roots(root)
    if not candidates:
        raise SystemExit(f"No Blender/NeRF dataset root found under {root}")
    lego_candidates = [path for path in candidates if "lego" in path.name.lower() or "lego" in str(path).lower()]
    return lego_candidates[0] if lego_candidates else candidates[0]


def prepare_output(source: Path, output: Path | None) -> Path:
    if output is None:
        return source

    output.mkdir(parents=True, exist_ok=True)
    for item in source.iterdir():
        target = output / item.name
        if item.is_dir():
            shutil.copytree(item, target, dirs_exist_ok=True)
        elif not target.exists() or item.stat().st_mtime > target.stat().st_mtime:
            shutil.copy2(item, target)
    return output


def ensure_test_split(dataset_root: Path) -> str:
    test = dataset_root / "transforms_test.json"
    if test.is_file():
        return "test"

    val = dataset_root / "transforms_val.json"
    if val.is_file():
        shutil.copy2(val, test)
        return "val copied to test"

    raise SystemExit(f"{dataset_root} needs transforms_test.json or transforms_val.json")


def resolve_image(dataset_root: Path, file_path: str) -> Path | None:
    normalized = file_path.replace("\\", "/").lstrip("./")
    candidate = dataset_root / normalized
    if candidate.suffix.lower() in IMAGE_EXTENSIONS and candidate.is_file():
        return candidate

    for extension in IMAGE_EXTENSIONS:
        with_extension = candidate.with_suffix(extension)
        if with_extension.is_file():
            return with_extension
    return None


def validate_transforms(dataset_root: Path, transforms_name: str) -> dict:
    path = dataset_root / transforms_name
    payload = json.loads(path.read_text(encoding="utf-8"))
    frames = payload.get("frames", [])
    if "camera_angle_x" not in payload:
        raise SystemExit(f"{path} is missing camera_angle_x")
    if not frames:
        raise SystemExit(f"{path} has no frames")

    missing = []
    for frame in frames:
        image = resolve_image(dataset_root, frame.get("file_path", ""))
        if image is None:
            missing.append(frame.get("file_path", ""))

    if missing:
        preview = ", ".join(missing[:5])
        raise SystemExit(f"{path} references {len(missing)} missing images. First missing: {preview}")

    return {"file": transforms_name, "frames": len(frames)}


def main() -> int:
    parser = argparse.ArgumentParser(description="Prepare a Drive-downloaded Lego NeRF/Blender dataset for training.")
    parser.add_argument("--download-root", required=True, type=Path, help="Folder downloaded from Google Drive.")
    parser.add_argument("--dataset-root", type=Path, help="Nested dataset folder if the download contains multiple folders.")
    parser.add_argument("--output", type=Path, help="Optional clean output folder to train from.")
    args = parser.parse_args()

    download_root = args.download_root.resolve()
    source = choose_root(download_root, args.dataset_root)
    dataset_root = prepare_output(source, args.output.resolve() if args.output else None)
    test_source = ensure_test_split(dataset_root)

    summary = {
        "source": str(source),
        "prepared_dataset": str(dataset_root),
        "test_split": test_source,
        "train": validate_transforms(dataset_root, "transforms_train.json"),
        "test": validate_transforms(dataset_root, "transforms_test.json"),
        "points3d_ply": str(dataset_root / "points3d.ply") if (dataset_root / "points3d.ply").is_file() else "will be generated by loader",
    }
    (dataset_root / "lego_dataset_summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
